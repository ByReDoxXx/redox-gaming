def svg(art: str) -> str:
    rows = [r for r in art.strip("\n").split("\n")]
    h = len(rows)
    w = max(len(r) for r in rows)
    paths = {}
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            c = row[x]
            if c in PALETTE:
                run = 1
                while x + run < len(row) and row[x + run] == c:
                    run += 1
                paths.setdefault(c, []).append(f"M{x} {y}h{run}v1h-{run}z")
                x += run
            else:
                x += 1
    body = "".join(f'<path fill="{PALETTE[c]}" d="{"".join(d)}"/>' for c, d in paths.items())
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w * 12}" height="{h * 12}" '
            f'shape-rendering="crispEdges">{body}</svg>\n')


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, art in ICONS.items():
        (OUT / f"{name}.svg").write_text(svg(art), encoding="utf-8")
        print("wrote", OUT / f"{name}.svg")


if __name__ == "__main__":
    main()
